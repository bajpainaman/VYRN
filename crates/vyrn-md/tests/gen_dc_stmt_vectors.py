#!/usr/bin/env python3
"""Writes dc_stmt_vectors.txt: statement-tree vectors for spec/10-accounts-risk-md.md §10
(the drop copy's statement leaf, the tree and its Merkle paths).

Independent of the Rust code: DC_EOD records are packed with `struct` from the §8.1 table,
leaves and nodes follow the §10 layout, and BLAKE3 comes from the `b3sum` CLI.

Lines: `eod <account> <book> <rec0> <rec1> <rec2> <rec3>` (records hex), then
`leaf <account> <leaf bytes hex> <leaf hash hex>`, `root <hash hex>`, and
`proof <account> <side><sibling hex>,...` (side R or L; `-` for none).

Usage: python3 -I gen_dc_stmt_vectors.py <out dir>
"""

import struct
import subprocess
import sys

EOD = 8
DURABLE = 4


def b3(body):
    return subprocess.run(["b3sum", "--no-names", "--raw"], input=body,
                          capture_output=True, check=True).stdout


def eod(account, ordinal, words):
    return struct.pack("<BBHI5Q", EOD, DURABLE, ordinal, account, *words)


def eod_hash(account, n, h):
    r = bytearray(eod(account, 3, [n, 0, 0, 0, 0]))
    r[16:48] = h
    return bytes(r)


def section(account, book, k):
    return (book, [
        eod(account, 0, [k, 10 * k, 3 * k, 1000 * k, 200 * k]),
        eod(account, 1, [(-5 * k) & (2**64 - 1), 2 * k, 0, 0, 0]),
        eod(account, 2, [7 + k, 8, 9 * k, 10, 0]),
        eod_hash(account, 4 + k, b3(b"stream %d %d" % (account, book))),
    ])


def leaf(account, sections):
    b = struct.pack("<BIH", 0, account, len(sections))
    for book, recs in sorted(sections):
        b += struct.pack("<H", book) + b"".join(recs)
    return b


def node(l, r):
    return b3(b"\x01" + l + r)


def tree(leaves):
    levels = [leaves]
    while len(levels[-1]) > 1:
        lv = levels[-1]
        levels.append([node(lv[i], lv[i + 1]) if i + 1 < len(lv) else lv[i]
                       for i in range(0, len(lv), 2)])
    return levels


def proof(levels, i):
    out = []
    for lv in levels[:-1]:
        j = i ^ 1
        if j < len(lv):
            out.append(("R" if j > i else "L", lv[j]))
        i //= 2
    return out


def main(out):
    # Five accounts out of order, one on two books, one with a zero section.
    accts = {
        0x1D: [section(0x1D, 7, 1)],
        0x03: [section(0x03, 7, 2), section(0x03, 2, 3)],
        0x40: [section(0x40, 7, 0)],
        0x2A: [section(0x2A, 7, 4)],
        0x07: [section(0x07, 7, 5)],
    }
    lines = []
    order = sorted(accts)
    leaves = []
    for a in order:
        for book, recs in accts[a]:
            lines.append("eod %d %d %s" % (a, book, " ".join(r.hex() for r in recs)))
        lb = leaf(a, accts[a])
        h = b3(lb)
        leaves.append(h)
        lines.append("leaf %d %s %s" % (a, lb.hex(), h.hex()))
    lv = tree(leaves)
    lines.append("root %s" % lv[-1][0].hex())
    for i, a in enumerate(order):
        p = proof(lv, i)
        lines.append("proof %d %s" % (a, ",".join(s + h.hex() for s, h in p) or "-"))
    lines.append("empty %s" % b3(b"").hex())
    with open(out + "/dc_stmt_vectors.txt", "w") as f:
        f.write("# generated by gen_dc_stmt_vectors.py; do not edit\n")
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
