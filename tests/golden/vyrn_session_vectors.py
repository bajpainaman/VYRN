#!/usr/bin/env python3
"""VYRN 04-protocol session-state vectors: what the lane does with a packet in each session state
(04 §3.1 V2/V7, §4.3), and the final in-stream record of each close cause. Standard library only.

The verdicts come from the 04 §4.3 state table and the 04 §3.1 check order alone, not from any
crate. Every packet in the table is otherwise valid: bound source, current epoch16, valid
tag_seq, pkt_seq = expected, a book of the session, and a live handle for the messages that take
one. One message per packet, at index 0.

Reading (spec gap, labelled): 04 §4.3 says `OPENING` accepts nothing because "V2 fails: the slot
is not yet live", but V2 in §3.1 and its pseudocode test only for `FREE`. These vectors take the
§4.3 row: an `OPENING` slot is dropped at V2 with no response, exactly like `FREE`.

Output, after `#` comments:
    <id> <state> <message> accept                    the packet is accepted and the message applied
    <id> <state> <message> drop                      no response, nothing recorded
    <id> <state> <message> oos <REASON> <detail>     dropped; out-of-stream Reject (index 0xFF)
    <id> <state> <message> reject <REASON> <detail>  accepted; in-stream Reject at index 0
    <id> close <CAUSE> <hex>                         the final in-stream record (01 §6.4 Reject)
"""
import struct

REASON = {"BAD_MAC": 1, "SESSION_CLOSED": 18}                      # 01 §6.5
CLOSE = [("LOGOUT", 1), ("BAD_MAC", 2), ("EQUIVOCATION", 3), ("ADMIN_KILL", 4),
         ("LANE_MOVED", 5), ("BOND", 6)]                            # 04 §4.3, PROTO_D_*
PROTO_D_DRAINING = 7
MSGS = ["New", "Cancel", "Reduce", "Replace", "Heartbeat", "ResendReq", "CancelAll"]
DRAINING_OK = {"Cancel", "Reduce", "CancelAll", "Heartbeat", "ResendReq"}   # 04 §4.3
CLOSED_CAUSE = 4                                                    # the CLOSED rows: ADMIN_KILL


def verdict(state, msg):
    if state in ("OPENING", "FREE"):
        return "drop"                                               # V2, §4.3
    if state == "CLOSED":
        return f"oos SESSION_CLOSED {CLOSED_CAUSE}"                 # V7: detail = close cause
    if state == "DRAINING" and msg not in DRAINING_OK:
        return f"reject SESSION_CLOSED {PROTO_D_DRAINING}"          # §4.3 DRAINING row
    return "accept"


def final_record(cause, value, pkt_seq=42):
    # 01 §6.4 Reject: type 0x83 | index 0xFF | reason u16 | detail u32 | 0 u32 | client_tag 0.
    # BAD_MAC closes with Reject BAD_MAC, detail = the offending pkt_seq; every other cause with
    # Reject SESSION_CLOSED, detail = the cause (04 §4.3).
    reason, detail = (REASON["BAD_MAC"], pkt_seq) if cause == "BAD_MAC" else \
        (REASON["SESSION_CLOSED"], value)
    return struct.pack("<BBHIII", 0x83, 0xFF, reason, detail, 0, 0)


print("# Generated by tests/golden/vyrn_session_vectors.py; see tests/golden/README.md.")
print(f"# CLOSED rows: the session was closed by ADMIN_KILL ({CLOSED_CAUSE}).")
n = 0
for state in ("OPENING", "ACTIVE", "DRAINING", "CLOSED", "FREE"):
    for msg in MSGS:
        n += 1
        print(f"S{n:02} {state} {msg} {verdict(state, msg)}")
print("# The final in-stream record of each close cause; BAD_MAC at pkt_seq 42.")
for i, (cause, value) in enumerate(CLOSE, 1):
    print(f"C{i:02} close {cause} {final_record(cause, value).hex()}")
